// Función para encontrar la mejor respuesta
export function findBestResponse(userMessage) {
  const messageLower = userMessage.toLowerCase();
  const words = messageLower.split(/\s+/);
  
  let bestMatch = null;
  let highestScore = 0;
  
  // Buscar en cada categoría
  for (const [category, data] of Object.entries(amarantoKnowledge)) {
    if (category === 'default') continue;
    
    let score = 0;
    
    // Contar coincidencias de keywords
    for (const keyword of data.keywords) {
      if (messageLower.includes(keyword)) {
        score += 1;
        // Dar más peso a coincidencias exactas de palabras completas
        if (words.includes(keyword)) {
          score += 2;
        }
      }
    }
    
    if (score > highestScore) {
      highestScore = score;
      bestMatch = data;
    }
  }
  
  // Si no hay coincidencia suficiente, usar respuesta por defecto
  if (highestScore === 0) {
    return amarantoKnowledge.default.response;
  }
  
  return bestMatch.response;
}

